/**
 * @file Polynomial.h
 * @brief Класс Polynomial — многочлен второй степени ax² + bx + c (вариант 5).
 * @details Объявление класса и подробная документация. Класс перенесён без
 * изменений из лабораторной работы №3 (репозиторий Lab3_OOP_try1) и собирается
 * в библиотеку lab3.
 * @author Vareshka86
 * @date 2026-10-03
 * @version 1.0
 */

#ifndef POLYNOMIAL_H
#define POLYNOMIAL_H

#include <ostream>
#include <string>

/**
 * @brief Многочлен не выше второй степени: ax² + bx + c.
 * @details Хранит три коэффициента a, b, c. Умеет вычислять значение в точке,
 * находить действительные корни и выводить себя в привычном виде, например
 * «2x² - 3x + 1».
 *
 * Инвариант: все коэффициенты — конечные числа (не бесконечность и не «не число»).
 * Его проверяют параметризованный конструктор и все операции, меняющие многочлен.
 *
 * Перегруженные операции (часть 2): `++` и `--` в префиксной и постфиксной форме
 * меняют все три коэффициента на 1; `+=` и `-=` складывают и вычитают многочлены;
 * `*=` и `/=` умножают и делят на число; бинарные `+`, `-`, `*`, `/` реализованы через
 * составное присваивание.
 *
 * Сравнения `<`, `>`, `<=`, `>=`, `==`, `!=` (часть 3) сравнивают значения многочленов
 * в общей точке x₀.
 *
 * Статические поля общие для всех многочленов:
 * - rootSearchCount_ — сколько раз с запуска программы искали корни (требование варианта 5);
 * - existingCount_ — сколько многочленов существует сейчас; его уменьшает деструктор;
 * - comparePoint_ — точка x₀, в которой сравниваются многочлены.
 */
class Polynomial
{
public:
    /// Значение, которое findRoots() возвращает, если корнем является любое число (0 = 0).
    static const int INFINITE_ROOTS = -1;

    /**
     * @brief Конструктор по умолчанию: нулевой многочлен 0x² + 0x + 0.
     */
    Polynomial();

    /**
     * @brief Параметризованный конструктор: многочлен ax² + bx + c.
     * @param a Коэффициент при x².
     * @param b Коэффициент при x.
     * @param c Свободный член.
     * @exception std::invalid_argument Если какой-то коэффициент — бесконечность
     *            или «не число». Объект в этом случае не создаётся.
     */
    Polynomial(double a, double b, double c);

    /**
     * @brief Конструктор копирования: новый многочлен с теми же коэффициентами.
     * @details Объявлен явно, потому что копия — это ещё один существующий
     * многочлен, и счётчик existingCount_ должен увеличиться.
     * @param other Многочлен, с которого снимается копия.
     */
    Polynomial(const Polynomial& other);

    /**
     * @brief Оператор присваивания: стандартное копирование коэффициентов.
     * @details Присваивание не создаёт новый объект, поэтому счётчик не меняется.
     * Объявлено явно (`= default`), потому что у класса свои конструктор
     * копирования и деструктор (правило трёх).
     * @param other Многочлен, коэффициенты которого присваиваются.
     * @return Ссылка на этот объект.
     */
    Polynomial& operator=(const Polynomial& other) = default;

    /**
     * @brief Деструктор: уменьшает счётчик существующих многочленов.
     * @details Динамической памяти класс не выделяет; деструктор нужен, чтобы
     * счётчик existingCount_ оставался верным при уничтожении объектов, в том
     * числе временных.
     */
    ~Polynomial();

    /**
     * @brief Возвращает коэффициент при x².
     * @return Коэффициент a.
     */
    double getA() const;

    /**
     * @brief Возвращает коэффициент при x.
     * @return Коэффициент b.
     */
    double getB() const;

    /**
     * @brief Возвращает свободный член.
     * @return Коэффициент c.
     */
    double getC() const;

    /**
     * @brief Вычисляет значение многочлена в точке x.
     * @details Используется схема Горнера: (a·x + b)·x + c — два умножения
     * вместо трёх.
     * @param x Точка.
     * @return Значение ax² + bx + c.
     */
    double valueAt(double x) const;

    /**
     * @brief Находит действительные корни уравнения ax² + bx + c = 0.
     * @details Разбирает все случаи:
     * - a ≠ 0 — квадратное уравнение: дискриминант D = b² − 4ac; при D > 0 два
     *   корня, при D = 0 один, при D < 0 действительных корней нет;
     * - a = 0, b ≠ 0 — линейное уравнение bx + c = 0: один корень −c / b;
     * - a = 0, b = 0, c ≠ 0 — корней нет;
     * - a = b = c = 0 — корень любое число (возвращается INFINITE_ROOTS).
     *
     * Каждый вызов увеличивает статический счётчик rootSearchCount_. Метод
     * константный: он не меняет коэффициенты, а статическое поле не является
     * частью объекта, поэтому менять его в const-методе можно.
     * @param[out] x1 Меньший корень (если корни есть).
     * @param[out] x2 Больший корень (если корней два; при одном корне — равен x1).
     * @return Число корней: 0, 1, 2 или INFINITE_ROOTS.
     */
    int findRoots(double& x1, double& x2) const;

    /**
     * @brief Записывает многочлен в привычном виде.
     * @details Нулевые слагаемые пропускаются, коэффициент 1 при x и x² не
     * пишется, знаки ставятся между слагаемыми: «2x² - 3x + 1», «-x² + 4», «0».
     * @return Строка с многочленом.
     */
    std::string toString() const;

    /**
     * @brief Префиксный инкремент `++p`: все коэффициенты увеличиваются на 1.
     * @details Сначала меняет объект, затем возвращает ссылку на него самого —
     * поэтому результат `++p` уже новый многочлен.
     * @return Ссылка на изменённый объект.
     * @exception std::overflow_error Если коэффициент перестанет быть конечным;
     *            многочлен не меняется.
     */
    Polynomial& operator++();

    /**
     * @brief Постфиксный инкремент `p++`: все коэффициенты увеличиваются на 1.
     * @details Параметр `int` не используется — он только отличает постфиксную
     * форму от префиксной. Сохраняет копию прежнего значения, меняет объект и
     * возвращает **копию прежнего** значения.
     * @return Многочлен, каким он был до увеличения.
     * @exception std::overflow_error Если коэффициент перестанет быть конечным.
     */
    Polynomial operator++(int);

    /**
     * @brief Префиксный декремент `--p`: все коэффициенты уменьшаются на 1.
     * @return Ссылка на изменённый объект.
     * @exception std::overflow_error Если коэффициент перестанет быть конечным.
     */
    Polynomial& operator--();

    /**
     * @brief Постфиксный декремент `p--`: все коэффициенты уменьшаются на 1.
     * @return Многочлен, каким он был до уменьшения.
     * @exception std::overflow_error Если коэффициент перестанет быть конечным.
     */
    Polynomial operator--(int);

    /**
     * @brief Прибавляет другой многочлен: `p += q` — коэффициенты складываются.
     * @param other Прибавляемый многочлен.
     * @return Ссылка на этот объект (позволяет писать `(p += q) += r`).
     * @exception std::overflow_error Если сумма коэффициентов перестанет быть
     *            конечной; многочлен не меняется.
     */
    Polynomial& operator+=(const Polynomial& other);

    /**
     * @brief Вычитает другой многочлен: `p -= q` — коэффициенты вычитаются.
     * @param other Вычитаемый многочлен.
     * @return Ссылка на этот объект.
     * @exception std::overflow_error Если разность перестанет быть конечной.
     */
    Polynomial& operator-=(const Polynomial& other);

    /**
     * @brief Умножает на число: `p *= k` — каждый коэффициент умножается на k.
     * @param k Множитель.
     * @return Ссылка на этот объект.
     * @exception std::invalid_argument Если k — бесконечность или «не число».
     * @exception std::overflow_error Если произведение перестанет быть конечным.
     */
    Polynomial& operator*=(double k);

    /**
     * @brief Делит на число: `p /= k` — каждый коэффициент делится на k.
     * @param k Делитель.
     * @return Ссылка на этот объект.
     * @exception std::invalid_argument Если k = 0 (деление на ноль), бесконечность
     *            или «не число»; многочлен не меняется.
     * @exception std::overflow_error Если частное перестанет быть конечным.
     */
    Polynomial& operator/=(double k);

    /**
     * @brief Сумма многочленов: `p + q`.
     * @details Реализована через `+=`, как требует задание: копия левого операнда
     * (параметр `lhs` передан по значению) увеличивается на правый и возвращается.
     * Сами p и q не меняются.
     * @param lhs Левый операнд (копия).
     * @param rhs Правый операнд.
     * @return Новый многочлен — сумма.
     */
    friend Polynomial operator+(Polynomial lhs, const Polynomial& rhs);

    /**
     * @brief Разность многочленов: `p - q`, через `-=`.
     * @param lhs Уменьшаемое (копия).
     * @param rhs Вычитаемое.
     * @return Новый многочлен — разность.
     */
    friend Polynomial operator-(Polynomial lhs, const Polynomial& rhs);

    /**
     * @brief Произведение многочлена на число: `p * k`, через `*=`.
     * @param lhs Многочлен (копия).
     * @param k   Множитель.
     * @return Новый многочлен.
     */
    friend Polynomial operator*(Polynomial lhs, double k);

    /**
     * @brief Произведение числа на многочлен: `k * p` — то же, что `p * k`.
     * @details Нужен отдельный оператор: в выражении `2 * p` слева стоит число,
     * а не многочлен.
     * @param k   Множитель.
     * @param rhs Многочлен (копия).
     * @return Новый многочлен.
     */
    friend Polynomial operator*(double k, Polynomial rhs);

    /**
     * @brief Частное многочлена и числа: `p / k`, через `/=`.
     * @param lhs Многочлен (копия).
     * @param k   Делитель.
     * @return Новый многочлен.
     * @exception std::invalid_argument Если k = 0.
     */
    friend Polynomial operator/(Polynomial lhs, double k);

    /**
     * @brief Меньше: `p < q`, если P(x₀) < Q(x₀).
     * @details Все шесть сравнений сравнивают **значения** многочленов в общей точке
     * сравнения x₀ (статическое поле comparePoint_, задаётся setComparePoint()),
     * как требует вариант 5. Значения считаются равными, если различаются меньше
     * чем на 10⁻¹³ относительно их величины: дробные вычисления дают погрешность.
     * Все сравнения выражены через одну функцию, поэтому всегда согласованы:
     * для любых p и q верно ровно одно из `p < q`, `p == q`, `p > q`.
     * @param lhs Левый многочлен.
     * @param rhs Правый многочлен.
     * @return true, если значение lhs в точке x₀ меньше значения rhs.
     */
    friend bool operator<(const Polynomial& lhs, const Polynomial& rhs);

    /**
     * @brief Больше: `p > q`, если P(x₀) > Q(x₀).
     * @param lhs Левый многочлен.
     * @param rhs Правый многочлен.
     * @return true, если значение lhs в точке x₀ больше.
     */
    friend bool operator>(const Polynomial& lhs, const Polynomial& rhs);

    /**
     * @brief Меньше или равно: `p <= q` — то же, что «не больше».
     * @param lhs Левый многочлен.
     * @param rhs Правый многочлен.
     * @return true, если P(x₀) ≤ Q(x₀).
     */
    friend bool operator<=(const Polynomial& lhs, const Polynomial& rhs);

    /**
     * @brief Больше или равно: `p >= q` — то же, что «не меньше».
     * @param lhs Левый многочлен.
     * @param rhs Правый многочлен.
     * @return true, если P(x₀) ≥ Q(x₀).
     */
    friend bool operator>=(const Polynomial& lhs, const Polynomial& rhs);

    /**
     * @brief Равно: `p == q`, если значения в точке x₀ совпадают.
     * @details Сравниваются значения, а не коэффициенты: разные многочлены могут
     * быть «равны» в данной точке (например, x² и x в точке 1).
     * @param lhs Левый многочлен.
     * @param rhs Правый многочлен.
     * @return true, если P(x₀) = Q(x₀) с учётом погрешности.
     */
    friend bool operator==(const Polynomial& lhs, const Polynomial& rhs);

    /**
     * @brief Не равно: `p != q` — отрицание `==`.
     * @param lhs Левый многочлен.
     * @param rhs Правый многочлен.
     * @return true, если значения в точке x₀ различаются.
     */
    friend bool operator!=(const Polynomial& lhs, const Polynomial& rhs);

    /**
     * @brief Задаёт точку x₀, в которой сравниваются многочлены.
     * @details Статический метод: точка одна для всех многочленов.
     * @param x Новая точка сравнения.
     * @exception std::invalid_argument Если x — бесконечность или «не число».
     */
    static void setComparePoint(double x);

    /**
     * @brief Возвращает текущую точку сравнения x₀.
     * @return Точка сравнения (по умолчанию 0).
     */
    static double getComparePoint();

    /**
     * @brief Возвращает, сколько раз с запуска программы искали корни.
     * @return Значение статического счётчика rootSearchCount_.
     */
    static int getRootSearchCount();

    /**
     * @brief Возвращает число существующих сейчас многочленов.
     * @return Значение статического счётчика existingCount_.
     */
    static int getExistingCount();

private:
    /**
     * @brief Записывает новые коэффициенты, если все они конечные.
     * @details Общая проверка для всех операций, меняющих многочлен: новые
     * значения сначала вычисляются отдельно, и только если все три конечные,
     * записываются в поля. Иначе бросается исключение, а многочлен остаётся прежним.
     * @param a Новый коэффициент при x².
     * @param b Новый коэффициент при x.
     * @param c Новый свободный член.
     * @exception std::overflow_error Если хотя бы одно значение не конечное.
     */
    void setCoefficients(double a, double b, double c);

    static int rootSearchCount_; ///< Сколько раз вызывали findRoots() (общее для всех объектов)
    static int existingCount_;   ///< Сколько объектов Polynomial существует сейчас
    static double comparePoint_; ///< Точка x₀, в которой сравниваются многочлены (общая для всех)

    double a_; ///< Коэффициент при x²
    double b_; ///< Коэффициент при x
    double c_; ///< Свободный член
};

/**
 * @brief Выводит многочлен в поток: `std::cout << p`.
 * @details Свободная функция, а не метод: слева от `<<` стоит поток, а не
 * многочлен. Использует открытый метод toString(), поэтому другом класса
 * быть не обязана.
 * @param out Поток вывода.
 * @param p   Многочлен.
 * @return Тот же поток — чтобы можно было писать `std::cout << p << '\n'`.
 */
std::ostream& operator<<(std::ostream& out, const Polynomial& p);

#endif // POLYNOMIAL_H
